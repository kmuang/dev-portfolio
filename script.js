const featuredProjectRank = new Map(featuredProjectTitles.map((title, index) => [title, index]));
const priorityProjectRank = new Map(priorityProjectTitles.map((title, index) => [title, index]));
const earlyWorkProjectRank = new Map(earlyWorkProjectTitles.map((title, index) => [title, index]));

projects.forEach((project, index) => {
    project.originalIndex = index;
    project.featured = featuredProjectRank.has(project.title);
    project.earlyWork = earlyWorkProjectRank.has(project.title);
});

projects.sort((a, b) => {
    const aRank = featuredProjectRank.get(a.title);
    const bRank = featuredProjectRank.get(b.title);
    const aPriorityRank = priorityProjectRank.get(a.title);
    const bPriorityRank = priorityProjectRank.get(b.title);
    const aEarlyRank = earlyWorkProjectRank.get(a.title);
    const bEarlyRank = earlyWorkProjectRank.get(b.title);

    if (aRank !== undefined && bRank !== undefined) return aRank - bRank;
    if (aRank !== undefined) return -1;
    if (bRank !== undefined) return 1;
    if (aPriorityRank !== undefined && bPriorityRank !== undefined) return aPriorityRank - bPriorityRank;
    if (aPriorityRank !== undefined) return -1;
    if (bPriorityRank !== undefined) return 1;
    if (aEarlyRank !== undefined && bEarlyRank !== undefined) return aEarlyRank - bEarlyRank;
    if (aEarlyRank !== undefined) return 1;
    if (bEarlyRank !== undefined) return -1;
    return a.originalIndex - b.originalIndex;
});

function renderProjectCards() {
    const grid = document.getElementById('projectsGrid');
    if (!grid) return;

    let earlyWorkDividerAdded = false;

    projects.forEach((project, index) => {
        if (project.earlyWork && !earlyWorkDividerAdded) {
            const divider = document.createElement('div');
            divider.className = 'project-group-divider';

            const dividerTitle = document.createElement('h3');
            dividerTitle.textContent = 'Early Work';

            const dividerText = document.createElement('p');
            dividerText.textContent = 'Older practice projects showing growth across layout, components, and JavaScript fundamentals.';

            divider.append(dividerTitle, dividerText);
            grid.appendChild(divider);
            earlyWorkDividerAdded = true;
        }

        const card = document.createElement('div');
        const projectSlug = project.title.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/(^-|-$)/g, '');
        card.className = `project-card project-card-${projectSlug}${project.featured ? ' project-card-featured' : ''}`;
        card.dataset.projectIndex = index;

        const imageWrap = document.createElement('div');
        imageWrap.className = 'project-image';

        const image = document.createElement('img');
        image.src = project.image;
        image.alt = project.alt;

        const overlay = document.createElement('div');
        overlay.className = 'project-overlay';

        const liveLink = document.createElement('a');
        liveLink.href = project.liveUrl;
        liveLink.target = '_blank';
        liveLink.rel = 'noopener';
        liveLink.className = 'btn-view';
        liveLink.textContent = 'View Project';

        const codeLink = document.createElement('a');
        codeLink.href = project.codeUrl;
        codeLink.target = '_blank';
        codeLink.rel = 'noopener';
        codeLink.className = 'btn-view';
        codeLink.textContent = 'View Code';

        overlay.append(liveLink, codeLink);
        imageWrap.append(image, overlay);

        const info = document.createElement('div');
        info.className = 'project-info';

        const title = document.createElement('h3');
        title.textContent = project.title;

        const summary = document.createElement('p');
        summary.className = 'project-summary';
        summary.textContent = project.summary;

        const tags = document.createElement('div');
        tags.className = 'project-tags';
        project.tags.forEach(tag => {
            const tagEl = document.createElement('span');
            tagEl.textContent = tag;
            tags.appendChild(tagEl);
        });

        info.append(title);
        if (project.featured && index === 0) info.appendChild(summary);
        info.appendChild(tags);
        card.append(imageWrap, info);
        grid.appendChild(card);
    });

    grid.addEventListener('click', event => {
        if (event.target.closest('a')) return;

        const card = event.target.closest('.project-card');
        if (!card) return;

        openModal(Number(card.dataset.projectIndex));
    });
}

renderProjectCards();

// Modal functions
function openModal(projectId) {
    const project = projects[projectId];
    if (!project) return;

    const modal = document.getElementById('projectModal');
    const modalLinks = modal.querySelectorAll('.modal-links a');

    document.getElementById('modalTitle').textContent = project.title;
    document.getElementById('modalDescription').textContent = project.description || `Built with ${project.tags.join(', ')}.`;
    document.getElementById('modalImage').src = project.image;
    document.getElementById('modalImage').alt = project.alt;

    const tagsContainer = document.getElementById('modalTags');
    tagsContainer.innerHTML = '';
    project.tags.forEach(tag => {
        const span = document.createElement('span');
        span.textContent = tag;
        tagsContainer.appendChild(span);
    });

    modalLinks[0].href = project.liveUrl;
    modalLinks[1].href = project.codeUrl;
    modal.classList.add('active');
    document.body.style.overflow = 'hidden';
}

function closeModal() {
    const modal = document.getElementById('projectModal');
    modal.classList.remove('active');
    document.body.style.overflow = 'auto';
}

// Close modal on background click
document.getElementById('projectModal').addEventListener('click', function (e) {
    if (e.target === this) {
        closeModal();
    }
});

// Contact form submission
document.getElementById('contactForm').addEventListener('submit', async function (e) {
    e.preventDefault();

    const formStatus = document.getElementById('formStatus');
    const submitButton = this.querySelector('.btn-submit');
    const originalButtonText = submitButton.textContent;

    formStatus.className = 'form-status';
    formStatus.textContent = '';
    submitButton.textContent = 'Sending...';
    submitButton.disabled = true;

    try {
        const response = await fetch(this.action, {
            method: this.method,
            body: new FormData(this),
            headers: {
                Accept: 'application/json'
            }
        });

        if (!response.ok) {
            throw new Error('Form submission failed');
        }

        formStatus.textContent = 'Thank you! Your message has been sent successfully.';
        formStatus.classList.add('show', 'success');
        this.reset();
    } catch (error) {
        formStatus.textContent = 'Sorry, your message could not be sent. Please try again or email me directly.';
        formStatus.classList.add('show', 'error');
    } finally {
        submitButton.textContent = originalButtonText;
        submitButton.disabled = false;

        setTimeout(() => {
            formStatus.className = 'form-status';
            formStatus.textContent = '';
        }, 5000);
    }
});

